import type { Role } from '@/types/domain';

/** Ответы «собеседника» mock-сервера — делают демо мессенджера живым. */
export function autoReplyFor(text: string, counterpartRole: Role, isSupport: boolean, hasAttachments: boolean): string {
  const t = text.toLowerCase();
  if (hasAttachments && !t.trim()) return 'Спасибо, получил! Посмотрю и вернусь с ответом.';
  if (isSupport) {
    if (/(парол|войти|вход)/.test(t)) return 'Подскажем! Попробуйте вход по Face ID или напишите email аккаунта — проверим доступ.';
    if (/(оплат|чек|деньг|тариф)/.test(t)) return 'По оплатам ответим в течение 10 минут. Пришлите, пожалуйста, номер чека.';
    return 'Спасибо, что написали! Специалист поддержки ответит в течение 10 минут.';
  }
  if (counterpartRole === 'buyer') {
    if (/(показ|посмотр|суббот|воскрес|время)/.test(t)) return 'Отлично, мне подходит. Подтвердите, пожалуйста, точное время.';
    return 'Спасибо! Подумаю и напишу вам сегодня.';
  }
  if (/(актуальн|продан|свободн)/.test(t)) return 'Да, объект актуален! Когда вам удобно посмотреть?';
  if (/(посмотр|показ|когда)/.test(t)) {
    return 'Можем показать в любой день с 10:00 до 19:00. Запишитесь через «Записаться на показ» — сразу подтвержу.';
  }
  if (/(торг|скидк|дешевл)/.test(t)) return 'Небольшой торг возможен после просмотра — обсудим на встрече.';
  if (/(рассроч|ипотек|кредит)/.test(t)) return 'Да, есть рассрочка до 24 месяцев без переплаты, объект подходит под ипотеку.';
  if (/(документ|кадастр|собствен)/.test(t)) return 'Все документы в порядке — покажу оригиналы на просмотре.';
  if (/(паркинг|парков)/.test(t)) return 'Подземный паркинг есть, место можно приобрести отдельно.';
  return 'Спасибо за сообщение! Отвечу подробнее в течение 15 минут.';
}

export function typingDurationFor(reply: string): number {
  return Math.min(3200, 900 + reply.length * 18);
}
